#!/usr/bin/env node
// Read the @table blocks in spec/FirstRunLab.tla and write
// ts/src/statechart.generated.ts. --check exits 1 when the file would change.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tlaPath = path.join(root, "spec", "FirstRunLab.tla");
const outPath = path.join(root, "ts", "src", "statechart.generated.ts");
const src = fs.readFileSync(tlaPath, "utf8");

const edge = /\[from\s*\|->\s*"([^"]+)"\s*,\s*why\s*\|->\s*"([^"]+)"\s*,\s*to\s*\|->\s*"([^"]+)"\s*\]/g;

function block(name) {
  const marker = `\\* @table ${name}`;
  const at = src.indexOf(marker);
  if (at < 0) throw new Error(`missing @table ${name} in ${tlaPath}`);
  const next = src.indexOf("\\* @table ", at + marker.length);
  const slice = src.slice(at, next < 0 ? src.length : next);
  const end = slice.indexOf("\n\n");
  const body = end < 0 ? slice : slice.slice(0, end);
  const rows = [];
  for (const m of body.matchAll(edge)) rows.push({ from: m[1], why: m[2], to: m[3] });
  if (!rows.length) throw new Error(`no edges in @table ${name}`);
  return rows;
}

const session = block("Session");
const run = block("Run");

function emit(rows) {
  return rows
    .map((r) => `  { from: ${JSON.stringify(r.from)}, why: ${JSON.stringify(r.why)}, to: ${JSON.stringify(r.to)} },`)
    .join("\n");
}

const states = [...new Set(session.flatMap((r) => [r.from, r.to]))];
const runStates = [...new Set(run.flatMap((r) => [r.from, r.to]))];

const text = `// Generated by tools/gen-statechart.mjs from spec/FirstRunLab.tla.
// Do not edit. CI regenerates this file and fails if it drifts.

export class IllegalTransition extends Error {
  constructor(message: string) {
    super(\`illegal \${message}\`);
    this.name = "IllegalTransition";
  }
}

export const SESSION_TABLE = [
${emit(session)}
] as const;

export const RUN_TABLE = [
${emit(run)}
] as const;

export const SESSION_STATES = ${JSON.stringify(states)} as const;
export type SessionState = (typeof SESSION_STATES)[number];

export const RUN_STATES = ${JSON.stringify(runStates)} as const;
export type RunState = (typeof RUN_STATES)[number];

export interface ChartEdge {
  from: string;
  why: string;
  to: string;
}

export function legal(table: readonly ChartEdge[], from: string, to: string, why: string): boolean {
  return table.some((t) => t.from === from && t.to === to && t.why === why);
}

export function assertSession(from: string, to: string, why: string): void {
  if (!legal(SESSION_TABLE, from, to, why)) throw new IllegalTransition(\`\${from} -\${why}-> \${to}\`);
}

export function assertRun(from: string, to: string, why: string): void {
  if (!legal(RUN_TABLE, from, to, why)) throw new IllegalTransition(\`run \${from} -\${why}-> \${to}\`);
}
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (cur !== text) {
    console.error("statechart.generated.ts is stale. Run: node tools/gen-statechart.mjs");
    process.exit(1);
  }
  console.log("statechart.generated.ts matches spec/FirstRunLab.tla");
} else {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, text);
  console.log(`wrote ${path.relative(root, outPath)} (${session.length} session edges, ${run.length} run edges)`);
}
